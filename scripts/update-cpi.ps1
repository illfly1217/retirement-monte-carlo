param([string]$AsOf = '2026-10-17')
$ErrorActionPreference = 'Stop'
# Official snapshots only; run deliberately when reviewing a new data release.
$cutoff = $AsOf.Substring(0,7)
$twdUrl = 'https://ws.dgbas.gov.tw/001/Upload/461/relfile/11525/230555/pr0101a1m.xml'
$usdUrl = 'https://fred.stlouisfed.org/graph/fredgraph.csv?id=CPIAUCNS'
[xml]$twdXml = (Invoke-WebRequest -Uri $twdUrl).Content
$twd = @($twdXml.DataSet.Obs | Where-Object { $_.Item -like '總指數*' -and $_.TYPE -eq '原始值' -and $_.FREQ -eq 'M' } | ForEach-Object {
  $month = $_.TIME_PERIOD -replace 'M','-'
  if($month -lt $cutoff -and $_.Item_VALUE -ne '') { @($month,[double]::Parse($_.Item_VALUE,[cultureinfo]::InvariantCulture)) }
})
$usdText = (& node --input-type=module -e "const r=await fetch(process.argv[1]);if(!r.ok)throw Error('CPI download failed: '+r.status);process.stdout.write(await r.text());" $usdUrl) -join "`n"
if($LASTEXITCODE -ne 0) { throw 'US CPI download failed.' }
$usd = @($usdText -split '\r?\n' | Select-Object -Skip 1 | ForEach-Object {
  $cols = $_ -split ',' | ForEach-Object { $_.Trim() }
  if($cols.Length -eq 2 -and $cols[0] -match '^\d{4}-\d{2}-01$' -and $cols[1] -match '^\d+(\.\d+)?$') {
    $month = $cols[0].Substring(0,7)
    if($month -ge '1981-01' -and $month -lt $cutoff) { @($month,[double]::Parse($cols[1],[cultureinfo]::InvariantCulture)) }
  }
})
# PowerShell enumerates nested arrays, so rebuild pairs explicitly.
function Series($flat,$name,$source,$license,$base) {
  $dates = @(); $levels = @()
  for($i=0; $i -lt $flat.Count; $i+=2) { $dates += $flat[$i]; $levels += $flat[$i+1] }
  if($dates.Count -lt 240) { throw "Insufficient CPI data: $name" }
  return [ordered]@{ name=$name; source=$source; license=$license; base=$base; dates=$dates; levels=$levels }
}
$data = [ordered]@{
  version=1; retrieved=$AsOf
  TWD=(Series $twd '行政院主計總處 · 台灣消費者物價總指數' $twdUrl 'https://data.gov.tw/license' '2021=100')
  USD=(Series $usd 'BLS · 美國 CPI-U 全項目未季調 CUUR0000SA0' $usdUrl 'https://www.bls.gov/opub/copyright-information.htm' '1982–1984=100')
}
$json = $data | ConvertTo-Json -Depth 8 -Compress
$root = Split-Path -Parent $PSScriptRoot
[IO.File]::WriteAllText((Join-Path $root 'dist/cpi-data.js'), "// Official CPI snapshots; regenerated by scripts/update-cpi.ps1.`nexport const CPI = $json;`n", [Text.UTF8Encoding]::new($false))
Write-Output "Saved official CPI snapshots: TWD $($data.TWD.dates.Count) levels, USD $($data.USD.dates.Count) levels."
